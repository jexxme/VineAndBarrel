function glyph(ch, rows) {
	const p = new opentype.Path();
	const width = Math.max(...rows.map((r) => r.length));
	const top = TOP[ch] ?? 0;
	rows.forEach((row, r) => {
		const yTop = (7 - r + top) * P;
		let x = 0;
		while (x < row.length) {
			if (row[x] !== '#') {
				x++;
				continue;
			}
			let x1 = x;
			while (x1 < row.length && row[x1] === '#') x1++;
			p.moveTo(x * P, yTop - P);
			p.lineTo(x1 * P, yTop - P);
			p.lineTo(x1 * P, yTop);
			p.lineTo(x * P, yTop);
			p.close();
			x = x1;
		}
	});
	return new opentype.Glyph({ name: `u${ch.codePointAt(0).toString(16)}`, unicode: ch.codePointAt(0), advanceWidth: (width + 1) * P, path: p });
}

