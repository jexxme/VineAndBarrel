const font = new opentype.Font({ familyName: 'FD Pixel', styleName: 'Regular', unitsPerEm: 10 * P, ascender: 8 * P, descender: -2 * P, glyphs });
fs.mkdirSync(path.join(SITE, 'public/fonts'), { recursive: true });
fs.writeFileSync(path.join(SITE, 'src/assets/fonts/fd-pixel.otf'), Buffer.from(font.toArrayBuffer()));
