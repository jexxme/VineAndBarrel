// Upkeep for the translated wiki (src/i18n/locales.mjs).
//   node scripts/i18n.mjs            write src/lib/l10n/<code>.ts, fix imports in translated pages, list UI strings
//   node scripts/i18n.mjs stamp <code> [page.mdx…]   record that these pages (default: all of that language) are
//                                    translated from the English as it is now
//   node scripts/i18n.mjs check      report (and exit 1 on) translated pages whose English changed since they were
//                                    stamped, pages never stamped, and UI strings a language is missing
//
// Translated pages are copies of the English ones under src/content/docs/<code>/, with the same imports; this script
// points them one folder deeper and swaps lib/data for lib/l10n/<code>, whose formatters and names are already in
// that language (days(), seconds(), nameOf()…), so the page's {expressions} stay exactly as in English.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import GithubSlugger from 'github-slugger';
import { LOCALES } from '../src/i18n/locales.mjs';

const SITE = path.resolve(import.meta.dirname, '..');
const DOCS = path.join(SITE, 'src/content/docs');
const SOURCES = path.join(SITE, 'src/i18n/sources.json');
const STRINGS = path.join(SITE, 'src/i18n/strings');
const codes = LOCALES.map((l) => l.code);
const rel = (p) => path.relative(SITE, p).replaceAll('\\', '/');
const walk = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir, { recursive: true }).map((f) => String(f).replaceAll('\\', '/')) : []);
const hash = (file) => crypto.createHash('sha1').update(fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n')).digest('hex').slice(0, 12);

/** English pages, relative to docs ("tipsy.mdx", "guides/cellar.mdx"). */
const englishPages = () => walk(DOCS).filter((f) => /\.mdx?$/.test(f) && !codes.includes(f.split('/')[0]));
const translatedPages = (code) => walk(path.join(DOCS, code)).filter((f) => /\.mdx?$/.test(f));

// ------------------------------------------------------------------ l10n modules
// Every helper of lib/data that prints words or numbers, bound to one language
const BOUND = `export const LOCALE = L;
export const nameOf = (id: string) => d.nameOf(id, L);
export const pageOf = (id: string) => d.pageOf(id, L);
export const pageUrl = (p: string) => d.pageUrl(p, L);
export const gameText = (key: string | null | undefined, en: string) => d.gameText(key, en, L);
export const seconds = (ticks: number) => d.seconds(ticks, L);
export const duration = (ticks: number) => d.duration(ticks, L);
export const days = (ticks: number) => d.days(ticks, L);
export const pct = (x: number, digits = 0) => d.pct(x, digits, L);
export const list = (xs: string[]) => d.list(xs, L);
export const num = (x: number, digits = 2) => d.num(x, L, digits);
export const t = (en: string, vars?: Record<string, string | number>) => tr(en, L, vars);`;
function writeModules() {
	const dir = path.join(SITE, 'src/lib/l10n');
	fs.mkdirSync(dir, { recursive: true });
	for (const code of codes) {
		const body = `// Generated by scripts/i18n.mjs: lib/data for translated pages in ${code}, its words and numbers in that language.
export * from '../data';
import * as d from '../data';
import { t as tr } from '../i18n';
const L = '${code}';
${BOUND}
`;
		const f = path.join(dir, `${code}.ts`);
		if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== body) fs.writeFileSync(f, body);
	}
}

// ------------------------------------------------------------------ imports in translated pages
function fixImports() {
	let fixed = 0;
	for (const code of codes) {
		for (const f of translatedPages(code)) {
			const file = path.join(DOCS, code, f);
			const src = fs.readFileSync(file, 'utf8');
			// Relative imports were written for the English page one folder up: resolve them from there
			const englishDir = path.dirname(path.join(DOCS, f));
			const out = src.replace(/(from\s+|import\s+)(['"])(\.{1,2}\/[^'"]+)\2/g, (m, kw, q, spec) => {
				let target = path.resolve(englishDir, spec);
				// Already pointing at the right place (fixed earlier)? Keep it.
				if (fs.existsSync(path.resolve(path.dirname(file), spec)) || fs.existsSync(path.resolve(path.dirname(file), spec) + '.ts')) {
					target = path.resolve(path.dirname(file), spec);
				}
				if (/[\\/]lib[\\/]data(\.ts)?$/.test(target)) target = path.join(SITE, 'src/lib/l10n', code);
				let r = path.relative(path.dirname(file), target).replaceAll('\\', '/');
				if (!r.startsWith('.')) r = './' + r;
				return `${kw}${q}${r}${q}`;
			})
				// Frontmatter: a translated title or description with ": " (or starting with a YAML sign) needs quotes
				.replace(/^(---\r?\n)([\s\S]*?)(\r?\n---)/, (m, a, fm, b) =>
					a +
					fm.replace(/^(title|description): (?!["'|>])(.*)$/gm, (l, k, v) => (/: |^[\[{&*!%@`#]| #/.test(v) ? `${k}: ${JSON.stringify(v.trim())}` : l)) +
					b,
				);
			if (out !== src) {
				fs.writeFileSync(file, out);
				fixed++;
			}
		}
	}
	if (fixed) console.log(`i18n: fixed imports in ${fixed} translated pages`);
}

// ------------------------------------------------------------------ heading anchors
// Translated pages keep the English headings' order and levels, so the n-th heading is the same section in every
// language. English anchors ("/tipsy/#rowdy") map to the translated ones by position: links written in a page are
// rewritten in place, and src/i18n/anchors.json lets pageUrl() map the anchors components link to.
const headingsOf = (file) => {
	const slugger = new GithubSlugger();
	const src = fs.readFileSync(file, 'utf8').replace(/^---[\s\S]*?\n---/, '').replace(/```[\s\S]*?```/g, '');
	return [...src.matchAll(/^(#{2,6})\s+(.+?)\s*#*\s*$/gm)].map((m) => {
		const text = m[2].replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[*_`]/g, '').replace(/<[^>]+>/g, '');
		return { level: m[1].length, slug: slugger.slug(text) };
	});
};
function mapAnchors() {
	const map = {};
	for (const { code } of LOCALES) {
		const pages = translatedPages(code);
		if (!pages.length) continue;
		map[code] = {};
		for (const f of pages) {
			const en = path.join(DOCS, f);
			if (!fs.existsSync(en)) continue;
			const a = headingsOf(en);
			const b = headingsOf(path.join(DOCS, code, f));
			const route = '/' + f.replace(/\.mdx?$/, '').replace(/(^|\/)index$/, '') + (f.match(/(^|\/)index\.mdx?$/) ? '' : '/');
			const same = a.length === b.length && a.every((h, i) => h.level === b[i].level);
			if (!same) {
				console.log(`i18n ${code}/${f}: headings don't line up with the English (${a.length} vs ${b.length}), anchors not mapped`);
				continue;
			}
			a.forEach((h, i) => h.slug !== b[i].slug && (map[code][`${route.replace(/\/\/$/, '/')}#${h.slug}`] = b[i].slug));
		}
		// Links written in the pages
		for (const f of pages) {
			const file = path.join(DOCS, code, f);
			const src = fs.readFileSync(file, 'utf8');
			const selfRoute = '/' + f.replace(/\.mdx?$/, '').replace(/(^|\/)index$/, '') + '/';
			const out = src.replace(/(\]\(|href=["'])(\/[^)"'#\s]*)?#([^)"'\s]+)/g, (m, open, p, anchor) => {
				const to = map[code][`${p ?? selfRoute}#${anchor}`];
				return to ? `${open}${p ?? ''}#${to}` : m;
			});
			if (out !== src) fs.writeFileSync(file, out);
		}
	}
	const file = path.join(SITE, 'src/i18n/anchors.json');
	const body = JSON.stringify(map, null, '\t') + '\n';
	if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== body) fs.writeFileSync(file, body);
}

// ------------------------------------------------------------------ UI strings
/** Every t('…') key in the code (literal first argument), with the files it's in. */
function uiStrings() {
	const keys = new Map();
	const files = walk(path.join(SITE, 'src')).filter((f) => /\.(astro|tsx?|mjs)$/.test(f) && !f.startsWith('lib/l10n/') && f !== 'lib/i18n.ts');
	// t('…') calls, and <Tr k="…"> sentences
	const re = /\bt\(\s*(['"`])((?:\\.|(?!\1).)*)\1|<Tr\b[^>]*?\sk=(["'])((?:(?!\3).)*)\3/gs;
	for (const f of files) {
		const src = fs.readFileSync(path.join(SITE, 'src', f), 'utf8');
		for (const m0 of src.matchAll(re)) {
			const m = m0[1] ? m0 : [m0[0], m0[3], m0[4]];
			if (m[1] === '`' && m[2].includes('${')) continue;
			const k = m[2].replace(/\\(['"`\\])/g, '$1');
			if (!keys.has(k)) keys.set(k, new Set());
			keys.get(k).add(f);
		}
	}
	// Ingredient tag labels ("Any copper") from the recipe data, printed by Slot.astro
	const recipes = fs.readFileSync(path.join(SITE, 'src/data/gen/recipes.json'), 'utf8');
	for (const m of recipes.matchAll(/"label":\s*"([^"]+)"/g)) {
		if (!keys.has(m[1])) keys.set(m[1], new Set());
		keys.get(m[1]).add('data/gen/recipes.json (Slot.astro)');
	}
	// The sidebar labels are UI strings too (src/i18n/sidebar.mjs reads them from the same files)
	const config = fs.readFileSync(path.join(SITE, 'astro.config.mjs'), 'utf8');
	const sidebar = config.slice(config.indexOf('sidebar:'));
	for (const m of sidebar.matchAll(/label:\s*(['"])((?:\\.|(?!\1).)*)\1/g)) {
		const k = m[2].replace(/\\(['"])/g, '$1');
		if (k === 'GitHub' || /Farmer's Delight Neoforged/.test(k)) continue;
		if (!keys.has(k)) keys.set(k, new Set());
		keys.get(k).add('sidebar');
	}
	return keys;
}
function writeStrings() {
	const keys = uiStrings();
	const out = Object.fromEntries([...keys].sort(([a], [b]) => a.localeCompare(b)).map(([k, fs_]) => [k, [...fs_].sort().join(', ')]));
	fs.writeFileSync(path.join(SITE, 'src/i18n/strings.en.json'), JSON.stringify(out, null, '\t') + '\n');
	return keys;
}

// ------------------------------------------------------------------ stamp and check
const readSources = () => (fs.existsSync(SOURCES) ? JSON.parse(fs.readFileSync(SOURCES, 'utf8')) : {});
function stamp(code, pages) {
	const sources = readSources();
	const list = pages.length ? pages : translatedPages(code);
	for (const f of list) {
		const en = path.join(DOCS, f);
		if (!fs.existsSync(en)) throw new Error(`No English page ${f}`);
		sources[`${code}/${f}`] = hash(en);
	}
	fs.writeFileSync(SOURCES, JSON.stringify(Object.fromEntries(Object.entries(sources).sort()), null, '\t') + '\n');
	console.log(`i18n: stamped ${list.length} ${code} pages`);
}
function check() {
	const sources = readSources();
	const keys = [...uiStrings().keys()];
	let problems = 0;
	const english = englishPages();
	for (const { code } of LOCALES) {
		const pages = translatedPages(code);
		if (!pages.length) continue;
		const stale = [];
		const unstamped = [];
		const orphan = [];
		for (const f of pages) {
			const en = path.join(DOCS, f);
			if (!fs.existsSync(en)) orphan.push(f);
			else if (!sources[`${code}/${f}`]) unstamped.push(f);
			else if (sources[`${code}/${f}`] !== hash(en)) stale.push(f);
		}
		const missingPages = english.filter((f) => !pages.includes(f));
		const dictFile = path.join(STRINGS, `${code}.json`);
		const dict = fs.existsSync(dictFile) ? JSON.parse(fs.readFileSync(dictFile, 'utf8')) : {};
		const missing = keys.filter((k) => !(k in dict));
		const parts = [];
		if (stale.length) parts.push(`English changed since translated: ${stale.join(', ')}`);
		if (unstamped.length) parts.push(`never stamped: ${unstamped.join(', ')}`);
		if (orphan.length) parts.push(`no English page: ${orphan.join(', ')}`);
		if (missingPages.length) parts.push(`not translated: ${missingPages.join(', ')}`);
		if (missing.length) parts.push(`${missing.length} UI strings missing (${missing.slice(0, 3).map((k) => JSON.stringify(k)).join(', ')}${missing.length > 3 ? '…' : ''})`);
		if (parts.length) {
			problems++;
			console.log(`i18n ${code}: ${parts.join('; ')}`);
		}
	}
	console.log(`i18n: ${LOCALES.filter((l) => translatedPages(l.code).length).length} languages, ${problems} with something to update`);
	return problems;
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === 'stamp') stamp(args[0], args.slice(1));
else if (cmd === 'check') process.exit(check() ? 1 : 0);
else {
	writeModules();
	fixImports();
	mapAnchors();
	const n = writeStrings().size;
	console.log(`i18n: ${n} UI strings (src/i18n/strings.en.json)`);
}
